export function localizeBadge<T extends Badge>(b: T, lang: Lang): T {
  if (lang === "en") return b;
  const t = BADGE_TEXT[b.id]?.[lang];
  return t ? { ...b, label: t.label, description: t.description } : b;
}

export function ratingKey(accuracy: number): RatingKey {
  if (accuracy === 100) return "flawless";
  if (accuracy >= 80) return "scholar";
  if (accuracy >= 60) return "seeker";
  if (accuracy >= 40) return "learner";
  return "starter";
}

export function localizeRating<T extends { title: string; message: string }>(r: T, accuracy: number, lang: Lang): T {
  if (lang === "en") return r;
  const t = RATING_TEXT[ratingKey(accuracy)]?.[lang];
  return t ? { ...r, title: t.title, message: t.message } : r;
}

export function localizeReward<T extends RewardDef | Reward>(r: T, lang: Lang): T {
  if (lang === "en") return r;
  const t = REWARD_TEXT[r.id]?.[lang];
  return t ? { ...r, ...t } : r;
}

/** Redeemed codes keep English in the database; shown in the player's language. */
export function localizeRedemption<T extends { rewardId: string; title: string; partner: string; discountLabel: string }>(r: T, lang: Lang): T {
  if (lang === "en") return r;
  const t = REWARD_TEXT[r.rewardId]?.[lang];
  return t ? { ...r, title: t.title, partner: t.partner, discountLabel: t.discountLabel } : r;
}
