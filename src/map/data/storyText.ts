interface JourneyPoint {
  city?: string;
  country?: string;
  description?: string;
  [key: string]: unknown;
}

interface StoryLike {
  id: string;
  title?: string;
  location?: string;
  description?: string;
  contributor?: string;
  person?: string;
  language?: string;
  journey?: JourneyPoint[];
  [key: string]: unknown;
}

/**
 * Return a copy of the story with its human-readable fields in `lang`.
 * id, category, coordinates, year and stage type are never changed, so
 * filters, colors and the API keep working.
 */
export function localizeStory<T extends StoryLike>(story: T, lang: SiteLang): T {
  if (!story || lang === "en") return story;
  const text = STORY_TEXT[story.id]?.[lang];
  const journey = Array.isArray(story.journey)
    ? story.journey.map((point, i) => ({
        ...point,
        city: localizePlace(point.city, lang),
        country: localizePlace(point.country, lang),
        description: text?.journey?.[i]?.description ?? point.description,
      }))
    : story.journey;
  return {
    ...story,
    title: text?.title ?? story.title,
    location: text?.location ?? story.location,
    description: text?.description ?? story.description,
    contributor: text?.contributor ?? story.contributor,
    person: text?.person ?? story.person,
    language: localizeLanguageName(story.language, lang),
    journey,
  };
}
