export function localizePlace(name: string | undefined, lang: SiteLang): string | undefined {
  if (!name || lang === "en") return name;
  return PLACE_NAMES[name]?.[lang] ?? name;
}

/** Translate a language name such as "Hindi / Punjabi" part by part. */
export function localizeLanguageName(name: string | undefined, lang: SiteLang): string | undefined {
  if (!name || lang === "en") return name;
  return name
    .split("/")
    .map((part) => {
      const key = part.trim();
      return LANGUAGE_NAMES[key]?.[lang] ?? key;
    })
    .join(" / ");
}

