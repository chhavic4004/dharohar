const DICTS: Record<SiteLang, Dict> = { en: EN, hi: HI, pa: PA, ur: UR };

export function siteText(lang: SiteLang, key: SiteKey, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? EN[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function useSiteT() {
  const lang = useLang();
  return useCallback((key: SiteKey, vars?: Record<string, string | number>) => siteText(lang, key, vars), [lang]);
}
